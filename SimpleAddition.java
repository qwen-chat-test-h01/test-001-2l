public class SimpleAddition {
    
    /**
     * 计算1+2并返回结果3
     * @return 1+2的结果
     */
    public static int addOneAndTwo() {
        return 1 + 2;
    }
    
    public static void main(String[] args) {
        int result = addOneAndTwo();
        System.out.println("1 + 2 = " + result);
    }
}
